import { expect, test } from '@playwright/test';

test('mobile mostra todas as abas da O.S. e conclusão abre em adicionar informações', async ({ page }, testInfo) => {
  await page.setViewportSize({ width:390, height:844 });
  await page.goto('./');
  await page.evaluate(() => window.eval(`
    currentAccount={company:{id:'qa-mobile',name:'QA'},user:{id:'qa-user',name:'QA',role:'admin',accessProfile:'admin',active:true}};
    document.body.classList.remove('auth-required','auth-loading','auth-restoring');
    document.body.classList.add('theme-light','premium-shell');
    createDemoDataSet();
    state.orders[0].status='Em execução';
    state.orders[0].startedAt=Date.now()-60000;
    state.orders[0].requester='Solicitante original';
    setView('orders');
    renderOrderDetail(state.orders[0]);
    applyPermissionVisibility();
  `));
  const panel=page.locator('#orders .os-detail-panel.has-order');
  await expect(panel.locator('> .order-execution-cta')).toHaveCount(0);
  await expect(panel.locator('.os-detail-actions').getByRole('button', {name:'Finalizar O.S.'})).toBeVisible();
  await expect(panel.locator('.os-detail-actions').getByRole('button', {name:'QR Code'})).toHaveCount(0);
  const tabs=panel.locator('.os-mobile-detail-tabs button');
  await expect(tabs).toHaveCount(14);
  await expect(tabs.first()).toBeVisible();
  await tabs.first().scrollIntoViewIfNeeded();
  await page.screenshot({ path:testInfo.outputPath('mobile-order-tabs.png') });
  await tabs.filter({hasText:'Materiais'}).click();
  await expect(page.locator('#genericModal.open #orderDetailForm [data-detail-tab="Materiais"]')).toHaveClass(/active/);
  await page.locator('#genericModal .close').click();
  await panel.locator('.os-detail-actions').getByRole('button', {name:'Finalizar O.S.'}).click();
  await expect(page.locator('#finishInfoTab')).toHaveAttribute('aria-selected','true');
  await expect(page.locator('#simpleFinishSolution')).toBeVisible();
  const finishTabs = page.locator('#simpleFinishForm [data-finish-detail-tab]');
  await expect(finishTabs).toHaveCount(14);
  await expect(finishTabs.filter({hasText:'Fotos'})).toBeVisible();
  await page.screenshot({ path:testInfo.outputPath('mobile-finish-info.png') });
  await page.locator('#finishRequestTab').click();
  await expect(page.locator('#finishRequestPanel')).toContainText('Solicitante original');
  await expect(page.locator('#simpleFinishSolution')).toBeHidden();
  await page.locator('#finishInfoTab').click();
  await expect(page.locator('#simpleFinishSolution')).toBeVisible();
});

test('foto é vinculada antes da conclusão e animação confirma a O.S. finalizada', async ({ page }) => {
  await page.setViewportSize({ width:390, height:844 });
  await page.goto('./');
  await page.evaluate(() => window.eval(`
    currentAccount={company:{id:'qa-finish',name:'QA'},user:{id:'qa-user',name:'QA',role:'admin',accessProfile:'admin',active:true}};
    document.body.classList.remove('auth-required','auth-loading','auth-restoring');
    document.body.classList.add('theme-light','premium-shell');
    createDemoDataSet();
    state.orders[0].status='Em execução';
    state.orders[0].startedAt=Date.now()-60000;
    saveState=()=>{};
    window.qaPhotoSaves=[];
    gmPersistState=async()=>{window.qaPhotoSaves.push(JSON.parse(JSON.stringify(state.orders[0].photos)));return true};
    window.qaFinishCalls=0;
    window.qaFinishShouldFail=true;
    gmTransitionWorkOrder=async(id,status,patch)=>{
      window.qaFinishCalls++;
      if(window.qaFinishShouldFail)throw Error('QA_TRANSITION_FAILED');
      state.orders=state.orders.map(order=>order.id===id?{...order,...patch,status}:order);
      return byId(state.orders,id);
    };
    setView('orders');
    openSimpleFinishOrderModal(state.orders[0].id);
  `));
  await page.locator('#simpleFinishForm [data-finish-detail-tab="Fotos"]').click();
  await expect(page.locator('#orderFileInput')).toBeVisible();
  await page.locator('#orderFileInput').setInputFiles({name:'evidencia.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScL/nwAAAABJRU5ErkJggg==','base64')});
  await page.locator('#orderFileAddBtn').click();
  await expect(page.locator('#detailTabPanel')).toContainText('evidencia.png');
  const photo = await page.evaluate(() => window.eval('state.orders[0].photos[0]'));
  expect(photo.dataUrl).toMatch(/^data:image\/png;base64,/);
  expect(await page.evaluate(() => window.eval('window.qaPhotoSaves[0][0].dataUrl'))).toBe(photo.dataUrl);
  await page.locator('#simpleFinishSolution').fill('Serviço concluído e fotografado');
  await page.locator('#simpleFinishForm button[type="submit"]').click();
  await expect(page.locator('#simpleFinishForm')).toBeVisible();
  await expect(page.locator('#orderSentConfirmation')).toHaveCount(0);
  await page.evaluate(() => window.eval('window.qaFinishShouldFail=false'));
  await page.locator('#simpleFinishForm button[type="submit"]').click();
  await expect(page.locator('#orderSentConfirmation')).toContainText('O.S. concluída com sucesso!');
  await expect(page.locator('#orderSentConfirmation button')).toHaveCount(0);
  await expect(page.locator('#genericModal')).not.toHaveClass(/open/);
  expect(await page.evaluate(() => window.eval('window.qaFinishCalls'))).toBe(2);
  expect(await page.evaluate(() => window.eval('state.orders[0].photos.length'))).toBe(1);
  await expect(page.locator('#orderSentConfirmation')).toHaveCount(0, {timeout:4000});
});
